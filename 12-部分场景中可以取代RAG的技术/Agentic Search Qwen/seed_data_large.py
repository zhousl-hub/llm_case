def generate_employees(n=100):
    used_names = set()
    employees = []
    for i in range(n):
        dept_info = random.choice(DEPARTMENTS)
        dept_name = dept_info["name"]
        positions = POSITIONS_BY_DEPT.get(dept_name, [("工程师", 15000, 30000)])
        position, salary_min, salary_max = random.choice(positions)
        name = _gen_name(used_names)
        salary = round(random.uniform(salary_min, salary_max), -2)

        employees.append({
            "name": name,
            "department": dept_name,
            "position": position,
            "email": _gen_email(name),
            "phone": _gen_phone(),
            "hire_date": _gen_date((2017, 2024)),
            "salary": salary,
            "status": random.choice(["active"] * 9 + ["inactive"]),
        })
    return employees


